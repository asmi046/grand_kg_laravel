    public function run(): void
    {
        $sectionIds = AuthorSection::query()->pluck('id', 'number');
        $subsectionIds = AuthorSubsection::query()->pluck('id', 'number');

        $orders = [];
        $titles = [];

        foreach ($this->companies() as $data) {
            $letter = Company::computeLetter($data['title']);
            $orders[$letter] = ($orders[$letter] ?? 0) + 1;

            $company = Company::updateOrCreate(
                ['title' => $data['title']],
                [
                    'letter' => $letter,
                    'order' => $orders[$letter],
                    'url' => $data['url'] ?? null,
                    'is_own_project' => $data['is_own_project'] ?? false,
                    'is_published' => true,
                    'year_from' => $data['year_from'] ?? null,
                    'year_to' => $data['year_to'] ?? null,
                    'region' => $data['region'] ?? null,
                ]
            );

            $titles[] = $company->title;

            $company->sections()->sync(
                $this->resolveIds($sectionIds, $data['sections'], 'раздел', $company)
            );

            $company->subsections()->sync(
                $this->resolveIds($subsectionIds, $data['subsections'], 'подраздел', $company)
            );
        }

        $this->removeOutdatedCompanies($titles);
    }

    /**
     * Найти идентификаторы разделов или подразделов по их номерам.
     *
     * @param  Collection<int|string, int>  $available
     * @param  array<int, int|string>  $numbers
     * @return array<int, int>
     */
    protected function resolveIds(Collection $available, array $numbers, string $type, Company $company): array
    {
        $ids = [];

        foreach ($numbers as $number) {
            if (! $available->has($number)) {
                $this->command?->warn('Компания «'.$company->title.'»: '.$type.' '.$number.' не найден');

                continue;
            }

            $ids[] = $available->get($number);
        }

        return $ids;
    }

    /**
     * Удалить компании, которых больше нет в исходных данных.
     *
     * @param  array<int, string>  $titles
     */
    protected function removeOutdatedCompanies(array $titles): void
    {
        Company::query()->whereNotIn('title', $titles)->delete();
    }

